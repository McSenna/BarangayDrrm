import assert from 'node:assert/strict';
import { assessmentStatusLabel, assessmentDamageLabel, canEditHouseholdAssessment, assessmentPayload, assessmentFormFor } from '../frontend/src/utils/householdAssessment.js';

assert.equal(assessmentStatusLabel({ status: 'pending_assignment' }), 'Pending Assignment');
assert.equal(assessmentStatusLabel({ status: 'assigned' }), 'Assigned / Pending Visit');
assert.equal(assessmentStatusLabel({ status: 'assessed' }), 'Assessed');
assert.equal(assessmentDamageLabel({ status: 'assigned', house_damage: 'None' }), 'Not Yet Assessed');
assert.equal(assessmentDamageLabel({ status: 'assessed', house_damage: 'None' }), 'No Damage — Assessed');
assert.equal(assessmentDamageLabel({ status: 'assessed', house_damage: 'Major' }), 'Major');
const row = { household_id: 5, assigned_field_officer_id: 7, status: 'assigned', version: 2 };
assert.equal(canEditHouseholdAssessment({ role: 'admin', user_id: 7 }, row), false);
assert.equal(canEditHouseholdAssessment({ role: 'relief_personnel', user_id: 7 }, row), false);
assert.equal(canEditHouseholdAssessment({ role: 'field_officer', user_id: 8 }, row), false);
assert.equal(canEditHouseholdAssessment({ role: 'field_officer', user_id: 7 }, row), true);
assert.throws(() => assessmentPayload(row, { findings: ' ', field_visit_date: '2026-10-16', house_damage: 'None' }), /findings/i);
assert.throws(() => assessmentPayload(row, { findings: 'Visited', field_visit_date: '', house_damage: 'None' }), /visit date/i);
assert.throws(() => assessmentPayload(row, { findings: 'Visited', field_visit_date: '2026-10-16', house_damage: '' }), /house damage/i);
const payload = assessmentPayload(row, { findings: ' Visited and checked roof ', field_visit_date: '2026-10-16', house_damage: 'None', remarks: '' });
assert.equal(payload.version, 2);
assert.equal(payload.household_id, 5);
assert.equal(payload.findings, 'Visited and checked roof');
assert.equal(payload.remarks, '');
const nextVisit = assessmentFormFor({ status: 'assigned', field_visit_date: '2026-10-01', findings: 'Previous visit', remarks: 'Old remarks', house_damage: 'Major', infrastructure_damage: 'Major' });
assert.equal(nextVisit.field_visit_date, '');
assert.equal(nextVisit.findings, '');
assert.equal(nextVisit.house_damage, '');
assert.equal(nextVisit.infrastructure_damage, 'None');
assert.equal(assessmentFormFor({ status: 'assessed', field_visit_date: '2026-10-16', house_damage: 'Minor', findings: 'Roof checked' }).findings, 'Roof checked');
console.log('PASS household assignment status, damage distinction, ownership and required visit details');
