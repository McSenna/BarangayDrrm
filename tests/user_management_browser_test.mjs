import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'C:/Users/Rivest/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fixture = JSON.parse(readFileSync('tests/.user-management-local/fixture.json', 'utf8'));
const createdName = `Browser Created ${Date.now()}`;
const editedName = createdName.replace('Created', 'Edited');
const php = spawn(process.env.PHP_BIN || 'C:/xampp/php/php.exe', ['-S', '127.0.0.1:8097', '-t', '.'], { env: { ...process.env, DB_NAME: fixture.database, DB_HOST: '127.0.0.1', CORS_ALLOWED_ORIGINS: 'http://127.0.0.1:5179' }, stdio: 'ignore' });
