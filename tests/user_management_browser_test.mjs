let browser;
let checks = 0;
const check = (ok, name) => { assert.ok(ok, name); checks++; console.log(`PASS ${name}`); };
try {
  for (let n = 0; n < 100; n++) { try { await fetch('http://127.0.0.1:5179'); break; } catch { await new Promise((r) => setTimeout(r, 150)); } }
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const login = await context.request.post(fixture.base + 'auth/login.php', { data: { email: 'admin@example.test', password: fixture.password } });
  assert.equal(login.status(), 200);
  const page = await context.newPage();
  const errors = []; page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('http://127.0.0.1:5179/admin/administrators?tab=all');
  await page.getByRole('button', { name: 'Test Administrator', exact: true }).waitFor();
  check(await page.getByRole('heading', { name: 'Users', exact: true }).isVisible(), 'Users renders with real authenticated API');
  await page.screenshot({ path: 'tests/.user-management-local/desktop.png', fullPage: true });
  await page.getByLabel('Search users').fill('Test street');
  await page.getByRole('button', { name: 'Edited Resident', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('.users-pagination')?.textContent.includes('1–1 of 1 users'));
  check(await page.locator('tbody tr').count() === 1, 'location search narrows table');
  check(await page.locator('tbody').getByText('Head of the family', { exact: true }).isVisible(), 'linked resident shows Head of the family in All accounts');
  await page.getByRole('button', { name: 'Edited Resident', exact: true }).click();
  check(await page.getByRole('dialog').isVisible(), 'details dialog opens');
  await page.keyboard.press('Escape');
  check(await page.getByRole('dialog').count() === 0, 'Escape closes dialog');
  await page.locator('tbody').getByRole('button', { name: 'Deactivate', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Deactivate', exact: true }).click();
  await page.locator('tbody').getByText('Deactivated', { exact: true }).waitFor();
  check(await page.locator('tbody').getByText('Head of the family', { exact: true }).isVisible(), 'deactivated household head remains visible in All accounts');
  await page.locator('tbody').getByRole('button', { name: 'Reactivate', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Reactivate', exact: true }).click();
  await page.locator('tbody').getByText('Active', { exact: true }).waitFor();
  await page.getByLabel('Search users').fill('');
  await page.getByRole('button', { name: 'Add user', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Full name').fill(createdName);
  const email = `browser${Date.now()}@example.test`;
  await dialog.getByLabel('Email', { exact: true }).fill(email);
  await dialog.getByLabel('Password', { exact: true }).fill('BrowserTestPassword12');
  await dialog.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('button', { name: createdName, exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: createdName, exact: true }).waitFor();
  check(true, 'create persists after browser refresh');
  await page.getByRole('button', { name: `Edit ${createdName}`, exact: true }).click();
  await page.getByRole('dialog').getByLabel('Full name').fill(editedName);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await page.getByRole('button', { name: editedName, exact: true }).waitFor();
  check(true, 'edit dialog persists profile');
  await page.getByLabel(`Select ${editedName}`, { exact: true }).check();
  await page.getByRole('button', { name: 'Deactivate selected', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Deactivate', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent.includes('1 account deactivated'));
  check(true, 'bulk confirmation persists deactivation');
  await page.getByRole('link', { name: /^Deactivated/ }).click();
  await page.getByRole('button', { name: editedName, exact: true }).waitFor();
  check(true, 'deactivated tab reflects mutation');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  check((await downloadPromise).suggestedFilename() === 'users.csv', 'CSV downloads');
  const applicantContext = await browser.newContext();
  const applicantPage = await applicantContext.newPage();
  await applicantPage.goto('http://127.0.0.1:5179/register');
  const applicantName = `Applicant ${Date.now()}`;
  const applicantEmail = `applicant${Date.now()}@example.test`;
  await applicantPage.getByLabel('Full Name', { exact: true }).fill(applicantName);
  await applicantPage.getByLabel('Email', { exact: true }).fill(applicantEmail);
  await applicantPage.getByLabel('Password (at least 6 characters)', { exact: true }).fill('ApplicantPassword12');
  await applicantPage.getByRole('button', { name: 'Register', exact: true }).click();
  await applicantPage.getByRole('status').filter({ hasText: 'wait for barangay approval' }).waitFor();
  check(await applicantPage.getByRole('dialog').count() === 0, 'registration confirms approval wait without opening login');
  check((await applicantContext.request.post(fixture.base + 'auth/login.php', { data: { email: applicantEmail, password: 'ApplicantPassword12' } })).status() === 403, 'new applicant cannot log in');
  await page.getByRole('link', { name: /^Requests/ }).click();
  await page.getByRole('button', { name: `Approve ${applicantName}`, exact: true }).waitFor();
  await page.screenshot({ path: 'tests/.user-management-local/requests-desktop.png', fullPage: true });
  await page.getByRole('button', { name: `Approve ${applicantName}`, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Approve registration', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Registration approved' }).waitFor();
  check((await applicantContext.request.post(fixture.base + 'auth/login.php', { data: { email: applicantEmail, password: 'ApplicantPassword12' } })).status() === 200, 'browser approval permits sign-in');
  const rejectedName = `Rejected ${Date.now()}`;
  await applicantContext.request.post(fixture.base + 'auth/register.php', { data: { full_name: rejectedName, email: `rejected${Date.now()}@example.test`, password: 'ApplicantPassword12' } });
  await page.getByRole('button', { name: 'Refresh users', exact: true }).click();
  await page.getByRole('button', { name: `Reject ${rejectedName}`, exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Reject registration', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Registration rejected' }).waitFor();
  await page.getByRole('link', { name: /^Rejected/ }).click();
  await page.getByRole('button', { name: rejectedName, exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: rejectedName, exact: true }).waitFor();
  check(true, 'rejected registration persists in Rejected tab after refresh');
  await applicantContext.close();
  for (const [width, name] of [[768, 'tablet'], [390, 'mobile']]) {
    await page.setViewportSize({ width, height: 900 });
    await page.screenshot({ path: `tests/.user-management-local/${name}.png`, fullPage: true });
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${name} has no page overflow`);
    check(await page.locator('.users-table-wrap').evaluate((el) => el.scrollWidth > el.clientWidth), `${name} table scrolls within region`);
  }
  await page.getByRole('button', { name: 'Add user', exact: true }).click();
  await page.screenshot({ path: 'tests/.user-management-local/mobile-dialog.png', fullPage: true });
  check(await page.getByRole('dialog').evaluate((el) => el.getBoundingClientRect().width < innerWidth), 'mobile dialog fits');
  await page.keyboard.press('Escape');
  check(errors.length === 0, `no JavaScript errors: ${errors.join('; ')}`);
  console.log(`PASS: ${checks} browser checks`);
} finally { await browser?.close(); php.kill(); vite.kill(); }
